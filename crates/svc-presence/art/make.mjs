// Builds the Rich Presence small-image SVGs: the tiles the app already
// draws, one per contract type (Contracts' catalog, `CATEGORY` in
// src/lib/modules/contracts/Catalog.svelte) and one per ship career
// (Ships, `LOOKS` in src/lib/modules/ships/careers.ts). Same glyph, same
// hue, same mixes as the app's `.tile`: the hue at 12% on --bg-raised, its
// edge at 26% on --border, the glyph at 85% on --text. Discord shows the
// small image as a circle, so the tile is a disc. Usage:
//   node make.mjs <lucide-svelte dist/icons dir> <out dir>
// Keep the lists in step with those two files and with
// `svc_presence::compose::asset`.
import fs from "node:fs";

const [lucideDir, outDir] = process.argv.slice(2);

// app.css tokens (src/app.css, dark theme).
const HUE = {
  rose: "#e485b2",
  apricot: "#ec9a63",
  sky: "#63b4e3",
  teal: "#48bfb6",
  sand: "#cbb37c",
  quality: "#48bfb6",
  accent: "#a996ff",
  dim: "#a19eac",
};
const BG_RAISED = "#1c1a23";
const BORDER = "#2b2934";
const TEXT = "#e7e6ec";

const TILES = {
  // Contract types (Catalog.svelte CATEGORY); `contract` is its fallback.
  contract_mercenary: ["crosshair", "rose"],
  contract_bounty_hunter: ["target", "apricot"],
  contract_delivery: ["package", "sky"],
  contract_hauling: ["truck", "teal"],
  contract_refueling: ["fuel", "sand"],
  contract_collection: ["boxes", "quality"],
  contract_investigation: ["search", "sky"],
  contract_maintenance: ["wrench", "sand"],
  contract_salvage: ["recycle", "quality"],
  contract_racing: ["flag", "apricot"],
  contract_priority: ["zap", "apricot"],
  contract_appointment: ["calendar-clock", "sky"],
  contract_service_beacons: ["radio", "rose"],
  contract: ["scroll-text", "dim"],
  // Ship careers (careers.ts LOOKS); `career` is its fallback.
  career_combat: ["crosshair", "rose"],
  career_gunship: ["target", "rose"],
  career_transport: ["package", "sand"],
  career_exploration: ["compass", "sky"],
  career_industrial: ["pickaxe", "apricot"],
  career_support: ["wrench", "teal"],
  career_competition: ["flag", "accent"],
  career_multi_role: ["layers", "accent"],
  career_starter: ["sparkles", "teal"],
  career_ground: ["truck", "sand"],
  career: ["rocket", "accent"],
};

/** `a` at `pct`% over `b`, in sRGB like CSS color-mix(in srgb, …). */
function mix(a, pct, b) {
  const c = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
  const [x, y] = [c(a), c(b)];
  return "#" + x.map((v, i) => Math.round((v * pct + y[i] * (100 - pct)) / 100).toString(16).padStart(2, "0")).join("");
}

const attrs = (o) => Object.entries(o).map(([k, v]) => `${k}="${v}"`).join(" ");

for (const [key, [name, hue]] of Object.entries(TILES)) {
  const src = fs.readFileSync(`${lucideDir}/${name}.svelte`, "utf8");
  const node = JSON.parse(src.match(/const iconNode = (\[.*\]);/)[1]);
  const glyph = node.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join("");
  const h = HUE[hue];
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 256 256">
  <!-- Starlume Rich Presence "${key}": the app's tile for it, lucide ${name}
       (ISC) in the ${hue} hue, as a disc. Generated by make.mjs. -->
  <circle cx="128" cy="128" r="128" fill="${mix(h, 12, BG_RAISED)}"/>
  <circle cx="128" cy="128" r="122" fill="none" stroke="${mix(h, 26, BORDER)}" stroke-width="12"/>
  <g transform="translate(50 50) scale(6.5)" fill="none" stroke="${mix(h, 85, TEXT)}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${glyph}</g>
</svg>
`;
  fs.writeFileSync(`${outDir}/${key}.svg`, svg);
}
console.log(Object.keys(TILES).length, "tiles");
